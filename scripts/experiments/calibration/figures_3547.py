"""Figures for #3547 -- does the acquisition offset's optimum move deeper?

Five figures, each answering something the tables cannot:

1. **the plateau, and that it replicated** -- Δcost against `prod` across the
   knob at both horizons.  The table gives six numbers per horizon; only the
   picture shows that the band across ``k = -3..-5`` is FLAT, which is the
   anchor the whole study hangs on.  If this shape had not come back, every
   deep reading would have been about the dataset instead of the horizon.
2. **which contrasts are readable** -- realised harvest per arm against the
   pre-registered 50% bar.  Compression is the study's central methodological
   fact and it is invisible in the DiD table's numbers; here the two excluded
   arms are the two over the line, and the shipped arm's clearance is the
   reason its contrast is the clean one.
3. **the DiD, as a forest** -- every H1 contrast with its CI against zero,
   clean ones solid and compressed ones hollow.  A table of nine rows makes
   the reader hold nine intervals in their head to see that the clean ones
   straddle zero; the figure is the finding in one glance.
4. **when spikes actually happen** -- first-spike times for the deep pile and
   for the H2 control on one axis, and incidence against harvest with #3319's
   point.  This is the H2 evidence and the reason the control exists: the deep
   pile's spikes are all EARLY, the control's are all LATE, and the control
   lands on #3319's number on the same commit.
5. **what the offset buys** -- clicks to the control's own final answer at both
   horizons.  The cost deltas are small and the speed ratio is not, and the
   ratio is the thing the shipped constant is actually worth.

Generated by committed code from the CSVs `frontier_3547.py --csv` and
`spike_timing_3547.py --csv` write, so the numbers in the report and the
numbers in the pictures cannot drift apart.

Usage::

    python figures_3547.py --csv <dir> [--ctrl <dir>] [--out <dir>]
"""

from __future__ import annotations

import argparse
from pathlib import Path

import matplotlib

matplotlib.use("Agg")

import matplotlib.pyplot as plt  # noqa: E402
import numpy as np  # noqa: E402
import pandas as pd  # noqa: E402
from matplotlib.lines import Line2D  # noqa: E402
from matplotlib.patches import Patch  # noqa: E402

#: The shipped stop in the colour that reads as "this is the one that ships".
SHIPPED = "acq_m4"
C_SHIP = "#b91c1c"
C_MAIN = "#334155"
C_MUTE = "#94a3b8"
C_WARN = "#c2410c"
C_REF = "#0f766e"
DPI = 130

#: #3319's deep wave, the reading this study exists to re-examine: `acq_m3`
#: spiked in 5.7% of cells at t=400 on a pile where it had consumed 82% of the
#: positives available to it.
REF_3319 = {"harvest": 0.82, "spike": 0.057, "label": "#3319 `acq_m3` @400 (prior study)"}

#: The pre-registered bar above which an arm's deep readings are compressed.
HARVEST_BAR = 0.50


def _lab(arm: str) -> str:
    return arm.replace("acq_m", "k=-").replace("acq_p", "k=+").replace("prod", "k=0")


def fig1_plateau(csv: Path, out: Path) -> None:
    d = pd.read_csv(csv / "frontier_3547_delta_vs_prod.csv")
    d = d[d["metric"] == "cost"]
    fig, ax = plt.subplots(figsize=(7.4, 4.6))
    for H, colour, marker, lab in (
        (100, C_MUTE, "o", "t=100 (the horizon every prior study used)"),
        (400, C_MAIN, "s", "t=400 (the deep session this study measures)"),
    ):
        s = d[d["horizon"] == H].sort_values("k")
        # `prod` is the reference and is 0 by construction; show it so the
        # plateau's left edge is visible rather than implied.
        k = np.concatenate([s["k"].to_numpy(), [0.0]])
        m = np.concatenate([s["mean"].to_numpy(), [0.0]])
        lo = np.concatenate([s["lo"].to_numpy(), [0.0]])
        hi = np.concatenate([s["hi"].to_numpy(), [0.0]])
        o = np.argsort(k)
        ax.errorbar(
            k[o],
            m[o],
            yerr=[m[o] - lo[o], hi[o] - m[o]],
            color=colour,
            marker=marker,
            capsize=3,
            lw=1.8,
            ms=6,
            label=lab,
        )
    ax.axhline(0, color="#64748b", lw=0.9, ls="--")
    ax.axvspan(-5.35, -2.65, color=C_SHIP, alpha=0.07)
    ax.set_ylim(-0.075, 0.095)
    ax.annotate(
        "the plateau — flat across k=-3..-5\n(#3319's shape, reproduced here)",
        xy=(-4.0, -0.068),
        ha="center",
        fontsize=8.5,
        color=C_SHIP,
    )
    ax.annotate(
        "k=-4 ships",
        xy=(-4, -0.042),
        xytext=(-2.6, 0.028),
        fontsize=8.5,
        color=C_SHIP,
        arrowprops={"arrowstyle": "->", "color": C_SHIP, "lw": 1.0},
    )
    ax.axvline(-4, color=C_SHIP, lw=1.0, ls=":")
    ax.set_xlabel("acquisition inclusion offset  k   (each step = one bit of evidence)")
    ax.set_ylabel("Δ final cost vs `prod`   (lower is better)")
    ax.set_title(
        "H3 — the plateau replicates on the deep pile, so the deep readings are about the HORIZON", fontsize=10
    )
    ax.legend(frameon=False, fontsize=9, loc="upper left")
    ax.grid(alpha=0.25, lw=0.6)
    fig.tight_layout()
    fig.savefig(out / "fig1_3547_plateau.png", dpi=DPI)
    plt.close(fig)


def fig2_compression(csv: Path, out: Path) -> None:
    d = pd.read_csv(csv / "frontier_3547_harvest.csv").sort_values("k")
    fig, ax = plt.subplots(figsize=(7.4, 4.4))
    colours = [C_WARN if c else (C_SHIP if a == SHIPPED else C_MAIN) for a, c in zip(d["arm"], d["compressed"])]
    x = np.arange(len(d))
    ax.bar(x, 100 * d["harvest_med"], color=colours, width=0.62)
    for i, (h, n) in enumerate(zip(d["harvest_med"], d["positives_400"])):
        ax.text(i, 100 * h + 1.6, "%.0f%%\n%d pos" % (100 * h, n), ha="center", fontsize=8, color="#334155")
    ax.axhline(100 * HARVEST_BAR, color=C_WARN, lw=1.4, ls="--")
    ax.text(
        len(d) - 0.45,
        100 * HARVEST_BAR + 2.0,
        "pre-registered bar — above this a tail is COMPRESSED",
        ha="right",
        fontsize=8.5,
        color=C_WARN,
    )
    ax.set_xticks(x)
    ax.set_xticklabels([_lab(a) for a in d["arm"]])
    ax.set_ylabel("median harvest @400  (positives found / available)")
    ax.set_title("Which contrasts are readable — compression, not effect size, excluded k=-5 and k=-6", fontsize=10)
    ax.set_ylim(0, 80)
    ax.legend(
        handles=[
            Patch(color=C_SHIP, label="k=-4, the shipped stop"),
            Patch(color=C_WARN, label="over the bar — deep reading is a lower bound only"),
            Patch(color=C_MAIN, label="readable"),
        ],
        frameon=False,
        fontsize=8.5,
        loc="upper right",
        bbox_to_anchor=(1.0, 0.87),
    )
    ax.grid(alpha=0.25, lw=0.6, axis="y")
    fig.tight_layout()
    fig.savefig(out / "fig2_3547_compression.png", dpi=DPI)
    plt.close(fig)


def fig3_did(csv: Path, out: Path) -> None:
    d = pd.read_csv(csv / "frontier_3547_did.csv")
    # cost and auc share a scale; ctt is in clicks and gets its own panel.
    fig, axes = plt.subplots(1, 2, figsize=(11.0, 4.0), gridspec_kw={"width_ratios": [1.45, 1]})
    for ax, metrics, xlab in (
        (axes[0], ["cost", "auc"], "DiD  [t=400 − t=100],  deep arm − k=-3"),
        (axes[1], ["ctt"], "DiD, clicks-to-target"),
    ):
        s = d[d["metric"].isin(metrics)].reset_index(drop=True)
        y = np.arange(len(s))[::-1]
        for yi, (_, r) in zip(y, s.iterrows()):
            clean = bool(r["clean"])
            colour = C_MAIN if clean else C_MUTE
            ax.plot([r["lo"], r["hi"]], [yi, yi], color=colour, lw=2.4, solid_capstyle="round")
            ax.plot(
                [r["mean"]],
                [yi],
                marker="o",
                ms=7.5,
                color=colour if clean else "white",
                markeredgecolor=colour,
                markeredgewidth=1.8,
                zorder=3,
            )
        ax.axvline(0, color=C_SHIP, lw=1.3, ls="--")
        ax.set_yticks(y)
        ax.set_yticklabels(
            [
                "%s  %s%s" % (_lab(r["deep_arm"]), r["metric"], "" if r["clean"] else "  (compressed)")
                for _, r in s.iterrows()
            ],
            fontsize=9,
        )
        ax.set_ylim(-0.7, len(s) - 0.3)
        ax.set_xlabel(xlab, fontsize=9.5)
        ax.grid(alpha=0.25, lw=0.6, axis="x")
    axes[0].ticklabel_format(axis="x", style="plain")
    axes[0].set_xticks([-0.005, 0.0, 0.005, 0.010, 0.015])
    axes[0].set_xticklabels(["-0.005", "0", "0.005", "0.010", "0.015"], fontsize=9)
    axes[0].set_title(
        "H1 — the optimum does not move: both clean intervals cover zero\n"
        "(negative would mean the deeper stop gains ground as the session runs on)",
        fontsize=10,
        loc="left",
    )
    axes[0].legend(
        handles=[
            Line2D([], [], color=C_MAIN, marker="o", lw=2.4, label="clean — neither arm compressed"),
            Line2D(
                [],
                [],
                color=C_MUTE,
                marker="o",
                lw=2.4,
                markerfacecolor="white",
                label="compressed — one-sided, excluded",
            ),
        ],
        frameon=False,
        fontsize=8.5,
        loc="lower left",
    )
    fig.tight_layout()
    fig.savefig(out / "fig3_3547_did.png", dpi=DPI)
    plt.close(fig)


def fig4_spikes(csv: Path, out: Path, ctrl: Path | None) -> None:
    cells = pd.read_csv(csv / "spike_timing_3547_cells.csv")
    spikes = pd.read_csv(csv / "frontier_3547_spikes.csv")
    harv = pd.read_csv(csv / "frontier_3547_harvest.csv").sort_values("k")
    fig, axes = plt.subplots(1, 2, figsize=(11.6, 4.6))

    # --- (a) when the first spike lands ---------------------------------------
    ax = axes[0]
    f = cells.dropna(subset=["first_t"])
    arms = list(harv["arm"])
    ylabels = []
    for i, arm in enumerate(arms):
        v = f[f["arm"] == arm]["first_t"].to_numpy(dtype=float)
        ylabels.append(_lab(arm))
        if not len(v):
            continue
        jitter = (np.random.default_rng(i).random(len(v)) - 0.5) * 0.30
        ax.scatter(
            v, np.full(len(v), i) + jitter, s=34, color=C_SHIP if arm == SHIPPED else C_MAIN, alpha=0.85, zorder=3
        )
    n_main = len(arms)
    n_early = int((f["first_t"] <= 100).sum())

    # the control on the same axis -- the contrast IS the H2 finding
    if ctrl is not None and (ctrl / "spike_timing_3547_cells.csv").exists():
        cf = pd.read_csv(ctrl / "spike_timing_3547_cells.csv").dropna(subset=["first_t"])
        ax.axhline(n_main - 0.5 + 0.5, color="#cbd5e1", lw=1.0)
        for j, arm in enumerate(["prod", "acq_m3"]):
            v = cf[cf["arm"] == arm]["first_t"].to_numpy(dtype=float)
            yi = n_main + 0.5 + j
            ylabels.append("%s  (control)" % _lab(arm))
            if not len(v):
                continue
            jitter = (np.random.default_rng(90 + j).random(len(v)) - 0.5) * 0.30
            ax.scatter(v, np.full(len(v), yi) + jitter, s=40, marker="^", color=C_REF, alpha=0.9, zorder=3)
        ax.set_yticks(list(range(n_main)) + [n_main + 0.5, n_main + 1.5])
        ax.set_ylim(-1.3, n_main + 2.7)
        ax.text(
            8,
            n_main + 2.05,
            "H2 CONTROL — shallow pile, same commit",
            fontsize=8.5,
            color=C_REF,
            ha="left",
            va="bottom",
        )
        ax.text(392, n_main - 0.8, "#3547 DEEP PILE", fontsize=8.5, color=C_MAIN, ha="right", va="top")
    else:
        ax.set_yticks(range(n_main))
        ax.set_ylim(-1.3, n_main - 0.3)
    ax.set_yticklabels(ylabels, fontsize=8.5)
    ax.axvline(100, color=C_WARN, lw=1.5, ls="--")
    ax.text(96, -0.85, "t=100", fontsize=8.5, color=C_WARN, ha="right")
    ax.set_xlabel("t of the cell's FIRST deep spike")
    ax.set_xlim(0, 400)
    ax.set_title(
        "(a) the deep pile spikes EARLY (%d of %d, none after t=100);\nthe exhausted control spikes LATE"
        % (n_early, len(cells)),
        fontsize=9.5,
        loc="left",
    )
    ax.grid(alpha=0.25, lw=0.6, axis="x")

    # --- (b) incidence against harvest ----------------------------------------
    ax = axes[1]
    s4 = spikes[spikes["horizon"] == 400].merge(harv[["arm", "harvest_med"]], on="arm", suffixes=("", "_h"))
    ax.scatter(
        100 * s4["harvest_med_h"],
        100 * s4["spike_frac"],
        s=70,
        color=C_MAIN,
        label="#3547 deep pile (this study)",
        zorder=3,
    )
    # nudge the two crowded low-harvest labels apart by hand
    nudge = {"prod": (5, -11), "acq_m1": (5, 4), "acq_p2": (-4, 6)}
    for _, r in s4.iterrows():
        ax.annotate(
            _lab(r["arm"]),
            (100 * r["harvest_med_h"], 100 * r["spike_frac"]),
            textcoords="offset points",
            xytext=nudge.get(r["arm"], (6, 4)),
            fontsize=8,
            color="#475569",
        )
    ax.scatter(
        [100 * REF_3319["harvest"]],
        [100 * REF_3319["spike"]],
        s=130,
        marker="D",
        color=C_WARN,
        zorder=4,
        label=REF_3319["label"],
    )
    if ctrl is not None and (ctrl / "frontier_3547_spikes.csv").exists():
        cs = pd.read_csv(ctrl / "frontier_3547_spikes.csv")
        cs = cs[cs["horizon"] == 400]
        ch = pd.read_csv(ctrl / "frontier_3547_harvest.csv")[["arm", "harvest_med"]]
        cs = cs.merge(ch, on="arm", suffixes=("", "_h"))
        ax.scatter(
            100 * cs["harvest_med_h"],
            100 * cs["spike_frac"],
            s=95,
            marker="^",
            color=C_REF,
            zorder=5,
            label="H2 control — shallow pile, THIS commit",
        )
        for _, r in cs.iterrows():
            ax.annotate(
                _lab(r["arm"]),
                (100 * r["harvest_med_h"], 100 * r["spike_frac"]),
                textcoords="offset points",
                xytext=(7, -11),
                fontsize=8,
                color=C_REF,
            )
    ax.annotate(
        "the control lands ON #3319's number\nat #3319's harvest — so the drop\nis the PILE, not 79 commits of dev",
        xy=(80, 5.4),
        xytext=(30, 3.1),
        fontsize=8.5,
        color=C_WARN,
        arrowprops={"arrowstyle": "->", "color": C_WARN, "lw": 1.0},
    )
    ax.set_xlabel("median harvest @400 (%)   — how much of the pool the arm consumed")
    ax.set_ylabel("cells with a deep spike (%)")
    ax.set_xlim(-3, 95)
    ax.set_ylim(0, 8.4)
    ax.set_title("(b) the deep hazard tracks EXHAUSTION, not aggression", fontsize=9.5, loc="left")
    ax.legend(frameon=False, fontsize=8.5, loc="upper left")
    ax.grid(alpha=0.25, lw=0.6)
    fig.tight_layout()
    fig.savefig(out / "fig4_3547_spikes.png", dpi=DPI)
    plt.close(fig)


def fig5_speed(csv: Path, out: Path) -> None:
    d = pd.read_csv(csv / "frontier_3547_speed.csv").sort_values("k")
    arms = list(dict.fromkeys(d["arm"]))
    x = np.arange(len(arms))
    fig, ax = plt.subplots(figsize=(7.6, 4.6))
    for H, off, colour, lab in ((100, -0.18, C_MUTE, "t=100"), (400, 0.18, C_MAIN, "t=400")):
        s = d[d["horizon"] == H].set_index("arm").reindex(arms)
        ax.bar(x + off, s["ctt_median"], width=0.34, color=colour, label=lab)
        for xi, (v, miss) in enumerate(zip(s["ctt_median"], s["miss_frac"])):
            if not np.isfinite(v):
                continue
            ax.text(xi + off, v + 4, "%.0f" % v, ha="center", fontsize=8, color="#334155")
            if miss >= 0.10:
                ax.text(
                    xi + off,
                    v + 15,
                    "%.0f%%\nnever" % (100 * miss),
                    ha="center",
                    fontsize=7,
                    color=C_WARN,
                    linespacing=0.95,
                )
    ax.set_xticks(x)
    ax.set_xticklabels([_lab(a) for a in arms])
    ax.set_ylim(0, 205)
    ax.set_ylabel("median clicks to `prod`'s own final answer")
    ax.set_title(
        "What the offset buys is SPEED: k=-4 reaches prod's 400-click answer in 44 clicks, not 154\n"
        "(orange = share of cells that never reach it at all)",
        fontsize=9.5,
        pad=10,
    )
    ax.legend(frameon=False, fontsize=9, loc="upper left")
    ax.grid(alpha=0.25, lw=0.6, axis="y")
    fig.tight_layout()
    fig.savefig(out / "fig5_3547_speed.png", dpi=DPI)
    plt.close(fig)


ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
ap.add_argument("--csv", type=Path, required=True, help="dir holding the analyzers' CSVs")
ap.add_argument("--ctrl", type=Path, default=None, help="the H2 control's CSV dir, overlaid on fig 4")
ap.add_argument("--out", type=Path, required=True)
a = ap.parse_args()
a.out.mkdir(parents=True, exist_ok=True)

fig1_plateau(a.csv, a.out)
fig2_compression(a.csv, a.out)
fig3_did(a.csv, a.out)
fig4_spikes(a.csv, a.out, a.ctrl)
fig5_speed(a.csv, a.out)
print("wrote 5 figures to %s" % a.out)
